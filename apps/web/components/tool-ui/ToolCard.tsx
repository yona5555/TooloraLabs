import { createElement, type CSSProperties } from "react";
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import Image from "next/image";
import { ArrowRight } from "lucide-react";
import { getLocale, getTranslations } from "next-intl/server";
import type { Tool } from "@/data/tools";
import { getToolIcon } from "@/lib/tool-icons";
import { Link } from "@/i18n/navigation";

/**
 * The one tool card used by every tool-listing surface: the /tools grid, a
 * category's grid, the homepage's featured tools and a tool page's related
 * tools. The inline-start half (mirrors in RTL) is the tool's
 * main drawing only (no inputs, buttons, tabs or tables), generated by
 * scripts/generate-tool-previews.mts (`npm run previews`): Arabic pages use the
 * ar images, every other locale the en images, and the light/dark pair is
 * swapped by the `dark` class so it always follows the site theme. Only images
 * locked in public/tool-previews/approved.json are shown, and only while the
 * file still matches its approved hash; the URL carries that hash (?v=) so a
 * browser or CDN never shows a stale image. The image is served as is
 * (unoptimized: the served bytes are the approved file), in a fixed 4:3 box,
 * object-fit: contain (never cover: it would crop the drawing), on the image's
 * own background so the letterbox is seamless. A tool without an approved image
 * shows a neutral icon placeholder, never a broken image. The other half holds
 * title, Featured badge, tags, description and the CTA.
 */

type ToolCardProps = {
  tool: Tool;
  titleText: string;
  descriptionText: string;
  /** Translated "Featured" label — shown only when both this and `tool.featured` are set. */
  featuredLabel?: string;
  maxTags?: number;
  /** 2 where the card list sits right under the page h1 (category pages), else 3 under a section h2. */
  headingLevel?: 2 | 3;
};

const previewDir = path.join(process.cwd(), "public/tool-previews");
type Approval = { sha256: string; bg: string };
const approved: Record<string, Record<string, Approval>> = existsSync(path.join(previewDir, "approved.json"))
  ? JSON.parse(readFileSync(path.join(previewDir, "approved.json"), "utf8"))
  : {};
const fileHash = new Map<string, string>();

/** The approved image of one variant, or null when it is not approved or the file differs from it. */
function approvedPreview(slug: string, set: "ar" | "en", theme: "light" | "dark") {
  const a = approved[slug]?.[`${set}/${theme}`];
  const file = path.join(previewDir, set, theme, `${slug}.webp`);
  if (!a || !existsSync(file)) return null;
  if (!fileHash.has(file)) fileHash.set(file, createHash("sha256").update(readFileSync(file)).digest("hex"));
  if (fileHash.get(file) !== a.sha256) return null;
  return { src: `/tool-previews/${set}/${theme}/${slug}.webp?v=${a.sha256.slice(0, 16)}`, bg: a.bg };
}

export default async function ToolCard({ tool, titleText, descriptionText, featuredLabel, maxTags = 2, headingLevel = 3 }: ToolCardProps) {
  const Heading = headingLevel === 2 ? "h2" : "h3";
  const t = await getTranslations("compareFinancialCalculators");
  const set = (await getLocale()) === "ar" ? "ar" : "en";
  const light = approvedPreview(tool.slug, set, "light");
  const dark = approvedPreview(tool.slug, set, "dark");
  const tags = tool.keywords.slice(0, maxTags);
  const showFeatured = tool.featured && featuredLabel;

  return (
    <Link
      href={`/tools/${tool.slug}`}
      className="group flex min-h-56 min-w-0 overflow-hidden rounded-2xl border border-zinc-200 bg-white shadow-md transition-all duration-300 hover:-translate-y-1 hover:border-blue-200 hover:shadow-xl focus-visible:outline-2 focus-visible:outline-blue-500 dark:border-zinc-800 dark:bg-zinc-900 dark:shadow-black/40 dark:hover:border-blue-500/40"
    >
      <div
        data-card-preview
        className="flex w-1/2 shrink-0 items-center border-e border-zinc-200 bg-[var(--pv-light)] dark:border-zinc-800 dark:bg-[var(--pv-dark)]"
        style={{ "--pv-light": light?.bg ?? "#ffffff", "--pv-dark": dark?.bg ?? "#18181b" } as CSSProperties}
      >
        {light && dark ? (
          <div className="relative aspect-[4/3] w-full">
            <Image src={light.src} alt={titleText} loading="lazy" unoptimized fill className="object-contain dark:hidden" style={{ backgroundColor: light.bg }} />
            <Image src={dark.src} alt={titleText} loading="lazy" unoptimized fill className="hidden object-contain dark:block" style={{ backgroundColor: dark.bg }} />
          </div>
        ) : (
          <div className="flex w-full items-center justify-center self-stretch bg-zinc-100 dark:bg-zinc-800">
            {createElement(getToolIcon(tool.slug), { size: 48, strokeWidth: 1.5, className: "text-zinc-400 dark:text-zinc-500", "aria-hidden": true })}
          </div>
        )}
      </div>

      <div className="flex min-w-0 flex-1 flex-col gap-2 p-3 sm:p-4">
        <Heading className="text-sm font-bold leading-snug text-zinc-900 sm:text-base dark:text-zinc-50">{titleText}</Heading>

        {(showFeatured || tags.length > 0) && (
          <div className="flex h-5 flex-wrap gap-1 overflow-hidden">
            {showFeatured && (
              <span className="rounded-full bg-blue-100 px-2 py-0.5 text-[10px] font-semibold leading-4 text-blue-700 dark:bg-blue-500/15 dark:text-blue-300">{featuredLabel}</span>
            )}
            {tags.map((tag) => (
              <span key={tag} className="min-w-0 rounded-full bg-zinc-100 px-2 py-0.5 text-[10px] font-medium leading-4 text-zinc-600 dark:bg-zinc-800 dark:text-zinc-300">
                {tag}
              </span>
            ))}
          </div>
        )}

        <p className="text-xs leading-snug text-zinc-500 dark:text-zinc-400">{descriptionText}</p>

        <span className="inline-flex w-fit max-w-full shrink-0 items-center gap-1 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-bold text-white transition-colors group-hover:bg-blue-700 dark:bg-blue-500 dark:group-hover:bg-blue-400 dark:group-hover:text-zinc-950">
          {t("openTool")}
          <ArrowRight size={12} className="rtl:rotate-180" aria-hidden="true" />
        </span>
      </div>
    </Link>
  );
}
