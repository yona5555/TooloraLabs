import { chromium } from "playwright";
const S = process.argv[2];
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = []; p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("http://localhost:3000/en/tools/scientific-calculator", { waitUntil: "load" });
await p.waitForTimeout(2500);
await p.screenshot({ path: `${S}/sc-top.png`, clip: { x: 160, y: 140, width: 780, height: 680 } });
const ex = p.locator('[data-testid="explorer-table"]');
await ex.scrollIntoViewIfNeeded(); await p.waitForTimeout(500);
const card = ex.locator("xpath=ancestor::div[contains(@class,'rounded-2xl')][1]");
await card.screenshot({ path: `${S}/sc-explorer.png` });
const read = () => p.evaluate(() => [...document.querySelectorAll('[data-testid="explorer-table"] [data-row]')].map((r) => r.textContent).join(" | "));
console.log("BEFORE", await read());
const h = p.locator('[data-testid="explorer-mafs"] .mafs-movable-point').first();
const bx = await h.boundingBox();
await p.mouse.move(bx.x + bx.width / 2, bx.y + bx.height / 2); await p.mouse.down();
await p.mouse.move(bx.x - 150, bx.y - 40, { steps: 6 });
console.log("DURING", await read());
await p.mouse.move(bx.x - 200, bx.y + 200, { steps: 6 });
console.log("DURING2", await read());
await p.mouse.up();
// sidebar drag
const uh = p.locator('[data-testid="uc-handle"]'); await uh.scrollIntoViewIfNeeded();
const ub = await uh.boundingBox(); const chips = () => p.locator('[data-testid="uc-chips"]').textContent();
console.log("UC BEFORE", await chips());
await p.mouse.move(ub.x + ub.width / 2, ub.y + ub.height / 2); await p.mouse.down();
await p.mouse.move(ub.x - 120, ub.y + 20, { steps: 6 });
console.log("UC DURING", await chips()); await p.mouse.up();
const hs = await p.evaluate(() => { const r = (s) => document.querySelector(s)?.getBoundingClientRect(); return { svg: r('[data-testid="uc-svg"]'), res: r('[data-tool-result]') }; });
console.log("svg bottom", hs.svg.bottom, "result bottom", hs.res.bottom, errs);
await b.close();
